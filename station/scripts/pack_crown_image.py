"""Embed the crown STM32 firmware into the station firmware: station/src/firmware/CrownImage.hpp.

At boot the station compares the crown's reported version with the embedded one and reflashes the crown through
its ROM I2C bootloader when they differ or the crown does not answer (blank chip): a station release always carries
the crown firmware it was tested with, and a factory-blank crown is programmed on first power-up.

Run after building the crown firmware:
    docker compose --profile lint run --rm -T cpp-lint "pio run -d crown -e crown"
    python3 station/scripts/pack_crown_image.py
Without crown/.pio/build/crown/firmware.bin an empty image is written (auto-update disabled).
"""

from __future__ import annotations

import inspect
import re
import sys
from pathlib import Path

_SCRIPT_FILE = Path(inspect.getfile(lambda: None)).resolve()
REPO = _SCRIPT_FILE.parents[2]
BIN = REPO / "crown/.pio/build/crown/firmware.bin"
MAIN = REPO / "crown/src/main.cpp"
OUT = REPO / "station/src/firmware/CrownImage.hpp"
MAX_IMAGE = 128 * 1024


def crown_version() -> tuple[int, int, int]:
    m = re.search(r"kVersion\{\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\}", MAIN.read_text())
    if not m:
        sys.exit(f"kVersion not found in {MAIN}")
    return int(m.group(1)), int(m.group(2)), int(m.group(3))


def build_header(image: bytes, version: tuple[int, int, int]) -> str:
    rows = [", ".join(f"0x{b:02x}" for b in image[i:i + 24]) for i in range(0, len(image), 24)]
    body = "\n".join(f"    {r}," for r in rows) if rows else "    0x00,"
    return "\n".join([
        "#pragma once",
        "// Generated by station/scripts/pack_crown_image.py from crown/.pio/build/crown/firmware.bin. Do not edit.",
        "// clang-format off",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace station {",
        "namespace firmware {",
        "",
        f"constexpr std::uint8_t kCrownImageVersion[3] = {{{version[0]}, {version[1]}, {version[2]}}};",
        f"constexpr std::size_t kCrownImageLen = {len(image)};   // 0 = no embedded image, auto-update off",
        "alignas(4) constexpr std::uint8_t kCrownImage[] = {",
        body,
        "};",
        "",
        "}  // namespace firmware",
        "}  // namespace station",
        "",
    ])


def main() -> None:
    image = BIN.read_bytes() if BIN.exists() else b""
    if len(image) > MAX_IMAGE:
        sys.exit(f"crown image {len(image)} B > {MAX_IMAGE} B")
    version = crown_version()
    OUT.write_text(build_header(image, version))
    print(f"{OUT.relative_to(REPO)}: crown fw {'.'.join(map(str, version))}, {len(image)} B")


if __name__ == "__main__":
    main()
