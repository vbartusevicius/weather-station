"""Pack station/data/{index.html,app.css,app.js} into station/src/firmware/WebAssets.hpp.

The Web UI is compiled into the firmware image (gzip, served with Content-Encoding: gzip), so the
UI and the JSON API it reads are always the same version, update and roll back together via OTA,
and need no filesystem. The LittleFS `storage` partition is reserved for station data (history).
Runs as a PlatformIO pre-build script and stand-alone: python3 station/scripts/pack_webui.py
"""

from __future__ import annotations

import gzip
import inspect
from pathlib import Path

_SCRIPT_FILE = Path(inspect.getfile(lambda: None)).resolve()
ROOT = _SCRIPT_FILE.parents[1]
DATA_DIR = ROOT / "data"
HEADER_OUT = ROOT / "src" / "firmware" / "WebAssets.hpp"

FILES = [
    ("index_html", DATA_DIR / "index.html"),
    ("app_css", DATA_DIR / "app.css"),
    ("app_js", DATA_DIR / "app.js"),
]


def c_array(data: bytes) -> str:
    rows = []
    for i in range(0, len(data), 24):
        rows.append("    " + ", ".join(f"0x{b:02x}" for b in data[i : i + 24]) + ",")
    return "\n".join(rows)


def build_cpp_header() -> str:
    lines = [
        "#pragma once",
        "// Generated by station/scripts/pack_webui.py from station/data/. Do not edit.",
        "// clang-format off",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace station {",
        "namespace firmware {",
        "namespace web_assets {",
        "",
    ]
    for ident, path in FILES:
        raw = path.read_bytes()
        gz = gzip.compress(raw, compresslevel=9, mtime=0)  # mtime=0: reproducible builds
        lines.append(f"// {path.name}: {len(raw)} bytes -> {len(gz)} bytes gzip")
        lines.append(f"static constexpr std::uint8_t {ident}_gz[] = {{")
        lines.append(c_array(gz))
        lines.append("};")
        lines.append(f"static constexpr std::size_t {ident}_gz_size = sizeof({ident}_gz);")
        lines.append("")
    lines += ["}  // namespace web_assets", "}  // namespace firmware", "}  // namespace station", "// clang-format on", ""]
    return "\n".join(lines)


def main() -> None:
    if not all(p.exists() for _, p in FILES):
        return
    HEADER_OUT.parent.mkdir(parents=True, exist_ok=True)
    hdr = build_cpp_header()
    if not HEADER_OUT.exists() or HEADER_OUT.read_text(encoding="utf-8") != hdr:
        HEADER_OUT.write_text(hdr, encoding="utf-8")


main()
