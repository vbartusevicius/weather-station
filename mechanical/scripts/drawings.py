def _profile_path(kind):
    """Full section (both halves mirrored) of a PTFE dome from build_enclosure.ptfe_dome_profile."""
    start, steps = be.ptfe_dome_profile(kind)

    def half(sign):
        out, prev = [f"M{_p(sign * start[0], start[1])}"], start
        for step in steps:
            if step[0] == "line":
                out.append(f"L{_p(sign * step[1][0], step[1][1])}")
            else:
                out.append(_svg_arc(prev, step[1], step[2], sign))
            prev = step[-1]
        return " ".join(out) + " Z"
    return f'<path d="{half(1)}" class="cut"/><path d="{half(-1)}" class="cut"/>'


def _svg_arc(a, m, b, sign):
    """SVG arc from a through m to b (radius from the circumcircle), mirrored by `sign`."""
    ax, ay = a
    bx, by = m
    cx, cy = b
    dd = 2 * (ax * (by - cy) + bx * (cy - ay) + cx * (ay - by))
    ux = ((ax * ax + ay * ay) * (by - cy) + (bx * bx + by * by) * (cy - ay) + (cx * cx + cy * cy) * (ay - by)) / dd
    uy = ((ax * ax + ay * ay) * (cx - bx) + (bx * bx + by * by) * (ax - cx) + (cx * cx + cy * cy) * (bx - ax)) / dd
    r = math.hypot(ax - ux, ay - uy) * S
    cross = (bx - ax) * (cy - ay) - (by - ay) * (cx - ax)   # > 0: counter-clockwise in model (y up) coordinates
    sweep = 0 if (cross > 0) == (sign > 0) else 1          # SVG y points down
    return f"A{r:.1f},{r:.1f} 0 0 {sweep} {_p(sign * cx, cy)}"


def ptfe_dome_svg(kind) -> str:
    f = be.UV_PTFE
    fr, tf, R, w = f["flange_r"], f["flange_t"], f["dome_r"], f["wall"]
    top = tf + (be.UV_PTFE_LATHE["height"] if kind == "lathe" else R)
    o = be.UV_DOME_ORING
    if kind == "lathe":
        title = "flanged PTFE dome, LATHE version (default, turned from round rod)"
        shape = (f"Shape: flange Ø {2 * fr:.1f} x {tf:.1f}, cylinder Ø {2 * R:.1f}, flat top, outer edge R "
                 f"{be.UV_PTFE_LATHE['edge_r']:.1f}, wall {w:.1f} ±0.05 (side, top, bore Ø {2 * (R - w):.1f}).")
        blank = "Blank: Ø 22-25 mm virgin PTFE rod. Plain turning + boring; no form tool needed."
    else:
        title = "flanged PTFE dome, CNC version (hemisphere, alternative)"
        shape = (f"Shape: flange Ø {2 * fr:.1f} x {tf:.1f}, hemisphere SR {R:.1f} centred on the flange top face, "
                 f"wall {w:.1f} ±0.05 (inner SR {R - w:.1f}, bore Ø {2 * (R - w):.1f}).")
        blank = "Blank: Ø 22-25 mm virgin PTFE rod. CNC turning with a sphere profile outside and inside."
    notes = [
        shape,
        (f"Flange FLAT on both faces: top = O-ring face ({o['id']:.0f} x {o['cs']:.1f} mm O-ring squeezed "
         f"{100 * (1 - o['squeezed'] / o['cs']):.0f} % against the crown lip), bottom = sits on the printed dome nut."),
        f"Tolerances: flange Ø {2 * fr:.1f} -0.1/+0 (bore Ø 20.8), flange faces flat/parallel 0.05, dome Ø {2 * R:.1f} ±0.05.",
        "Material: virgin (unfilled, non-porous) white PTFE. NOT glass/carbon-filled, NOT sintered optical PTFE. " + blank,
        ("Order: PCBWay CNC turning (material PTFE, white) with the matching ptfe_dome_*.step + this drawing, an "
         "AliExpress custom-PTFE turning shop, or any lathe. Fine-turned matte finish; no polish (PTFE stays milky), "
         "no coating, no oil."),
        f"Diffuse transmission ~10-12 % at 250-1100 nm through the {w:.1f} mm wall (firmware optics_transmission 0.11).",
    ]
    dims = (_dim_h(-fr, fr, 0.0, f"Ø {2 * fr:.1f}", 34)
            + _dim_h(-(R - w), R - w, 0.0, f"Ø {2 * (R - w):.1f}", 62)
            + _dim_h(-R, R, top, f"Ø {2 * R:.1f}" if kind == "lathe" else f"SR {R:.1f}", -24)
            + _dim_v(fr, 0.0, tf, f"{tf:.1f}", 30)
            + _dim_v(fr, 0.0, top, f"{top:.2f}", 110)
            + _dim_v(0.0, top - w, top, f"{w:.1f}", 40)
            + f'<line x1="{OX}" y1="{OY + 50}" x2="{OX}" y2="{OY - (top + 2) * S}" class="axis"/>')
    lines = []
    for n, note in enumerate(notes, start=1):
        for m, part in enumerate(textwrap.wrap(note, 112)):
            lines.append(f"{n}. {part}" if m == 0 else f"    {part}")
    notes_svg = "".join(f'<text x="40" y="{430 + 17 * i}" class="n" xml:space="preserve">{s}</text>' for i, s in enumerate(lines))
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="900" height="640" viewBox="0 0 900 640">
<defs><marker id="a" viewBox="0 0 10 10" refX="5" refY="5" markerWidth="6" markerHeight="6" orient="auto-start-reverse">
<path d="M0,2 L10,5 L0,8 z"/></marker>
<pattern id="h" width="6" height="6" patternUnits="userSpaceOnUse" patternTransform="rotate(45)"><line x1="0" y1="0" x2="0" y2="6" stroke="#333" stroke-width="1"/></pattern></defs>
<style>.cut{{fill:url(#h);stroke:#000;stroke-width:1.5}}.dim{{stroke:#06c;stroke-width:1}}.ext{{stroke:#06c;stroke-width:0.6}}
.axis{{stroke:#999;stroke-dasharray:12 4 2 4}}.t{{font:13px sans-serif;fill:#06c}}.n{{font:12px sans-serif}}.title{{font:bold 17px sans-serif}}</style>
<rect x="5" y="5" width="890" height="630" fill="#fff" stroke="#000"/>
<text x="40" y="40" class="title">AeroMet V1 — {title}</text>
<text x="40" y="62" class="n">Section through the axis. All dimensions in mm. Scale ~12:1. Generated by mechanical/scripts/drawings.py.</text>
{_profile_path(kind)}{dims}{notes_svg}
</svg>
'''


def export_drawings(out_dir: Path) -> None:
    out = Path(out_dir) / "drawings"
    if out.exists():
        for old in out.glob("*.svg"):
            old.unlink()
    out.mkdir(parents=True, exist_ok=True)
    (out / "jgs1_window.svg").write_text(window_svg())
    for kind in ("lathe", "cnc"):
        (out / f"ptfe_dome_{kind}.svg").write_text(ptfe_dome_svg(kind))
    print(f"Exported drawings/jgs1_window.svg, ptfe_dome_lathe.svg, ptfe_dome_cnc.svg -> {out}")


if __name__ == "__main__":
    export_drawings(Path(__file__).resolve().parents[1] / "build" / "v1")
