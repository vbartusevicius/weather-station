"""Purchase drawings for the non-electronic optical parts (SVG, mm), written next to the enclosure exports.

ptfe_dome_lathe.svg / ptfe_dome_cnc.svg: the two flanged PTFE dome diffusers for the `crown` top (lathe version from
round rod = default, CNC hemisphere version), drawn from build_enclosure.ptfe_dome_profile (checklist N3).
jgs1_window.svg: the backup stock Ø 20 x 2 mm JGS1 fused-silica UV window for the `crown_window` top (checklist B3 /
M13). The numbers come from build_enclosure.UV_WIN / UV_NUT_TOP / UV_BOSS.
"""

from __future__ import annotations

import math
import sys
